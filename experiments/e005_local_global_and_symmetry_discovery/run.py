def entropy(counts):
    p = counts[counts > 0] / counts.sum()
    return float(-(p * np.log2(p)).sum())


def mutual_info(C, j, S):
    """I(X_j ; X_S) under the uniform distribution on codewords C, exactly."""
    S = list(S)
    keyS = (C[:, S].astype(np.int64) << np.arange(len(S))).sum(1) if S else np.zeros(len(C), np.int64)
    joint = keyS * 2 + C[:, j]
    hS = entropy(np.bincount(keyS)); hJ = entropy(np.bincount(C[:, j])); hSJ = entropy(np.bincount(joint))
    return hS + hJ - hSJ


def local_global_profile(C, rng, samples=300):
    octads = [frozenset(np.nonzero(w)[0]) for w in C if w.sum() == 8]
    prof = []
    for k in range(0, 12):
        vals = []
        for _ in range(samples):
            j = int(rng.integers(24))
            S = rng.choice([i for i in range(24) if i != j], k, replace=False)
            vals.append(mutual_info(C, j, S))
        # constructive max at k = 7: complete an octad
        mx = max(vals)
        if k == 7:
            O = sorted(octads[0]); mx = max(mx, mutual_info(C, O[0], O[1:]))
        prof.append({"k": k, "mean_bits": float(np.mean(vals)), "max_bits": float(mx)})
        print(f"  k={k:>2}: mean I = {np.mean(vals):.4f}  max I = {mx:.4f}", flush=True)
    return prof


# ── symmetry discovery ───────────────────────────────────────────────────────

def blocks_from_span(words):
    basis = {}
    for w in words:
        v = int(sum(int(b) << i for i, b in enumerate(w)))
        for p in sorted(basis, reverse=True):
            if v >> p & 1:
                v ^= basis[p]
        if v:
            basis[v.bit_length() - 1] = v
    span = [0]
    for b in basis.values():
        span += [s ^ b for s in span]
    return len(basis), [frozenset(i for i in range(24) if s >> i & 1) for s in span if bin(s).count("1") == 8]


def random_automorphism(blocks, rng, max_nodes=200_000):
    """Random permutation of 24 points mapping the block system onto itself, by DFS with propagation.
    Uses: if >= 5 points of a block B are assigned and their images lie in a unique block B', then
    sigma(B) = B' (Steiner property, checked on the fly), so points of B map into B' and others outside."""
    bset = set(blocks)
    by5 = {}
    for B in blocks:
        for f in itertools.combinations(sorted(B), 5):
            by5.setdefault(frozenset(f), []).append(B)
    steiner = all(len(v) == 1 for v in by5.values()) and len(by5) == math.comb(24, 5)
    order = list(range(24)); nodes = [0]

    def dfs(sig, dom):
        nodes[0] += 1
        if nodes[0] > max_nodes:
            return None
        if len(sig) == 24:
            return sig if all(frozenset(sig[i] for i in B) in bset for B in blocks) else None
        x = min((i for i in order if i not in sig), key=lambda i: len(dom[i]))
        cands = list(dom[x]); rng.shuffle(cands)
        for y in cands:
            s2 = dict(sig); s2[x] = y
            d2 = {i: set(dom[i]) - {y} for i in dom if i not in s2}
            ok = True
            if steiner:
                for B in blocks:
                    if x in B:
                        assigned = [i for i in B if i in s2]
                        if len(assigned) >= 5:
                            img = frozenset(s2[i] for i in assigned[:5])
                            Bp = by5.get(img)
                            if not Bp or any(s2[i] not in Bp[0] for i in assigned):
                                ok = False; break
                            for i in d2:
                                d2[i] &= Bp[0] if i in B else (set(range(24)) - Bp[0])
                                if not d2[i]:
                                    ok = False; break
                            if not ok:
                                break
            if ok and all(d2[i] for i in d2):
                r = dfs(s2, d2)
                if r is not None:
                    return r
        return None

    return dfs({}, {i: set(range(24)) for i in range(24)}), steiner


def discover(C, Ns, rng):
    out = []
    for N in Ns:
        train = C[rng.integers(0, 4096, N)]
        dim, blocks = blocks_from_span(train)
        rec = {"N": N, "span_dim": dim, "weight8_blocks": len(blocks)}
        if len(blocks) == 759:
            gens, t0 = [], time.time()
            for _ in range(4):
                s, steiner = random_automorphism(blocks, rng)
                if s:
                    gens.append(Permutation([s[i] for i in range(24)]))
            G = PermutationGroup(gens)
            rec.update({"steiner_S(5,8,24)": steiner, "generators_found": len(gens), "group_order": int(G.order()),
                        "transitivity_degree": int(G.transitivity_degree), "seconds": round(time.time() - t0, 1)})
            rec["contains_the_PSL(2,23)_we_handed_it"] = bool(all(G.contains(Permutation([int(i) for i in g])) for g in
                                                                   [np.argsort(g) for g in e002.group_generators()]))
        out.append(rec)
        print("  ", rec, flush=True)
    return out


