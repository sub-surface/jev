"""E005 — Local-to-global obstruction, and discovering the symmetry group from data.

A. LOCAL-GLOBAL PROFILE (the measurable shadow of 'cohomology of the target').
   For the Golay code, compute EXACTLY (enumerating all 4096 codewords) the information a k-local observer has
   about one bit: I(X_j ; X_S) for |S| = k, both the mean over random S and the max over S. Prediction from the
   dual distance (8): every set of <= 7 coordinates is exactly uniform, so I = 0 for all k <= 6, and a jump to
   1 bit at k = 7 exactly when S ∪ {j} is an octad. Information exists only globally.
B. SYMMETRY DISCOVERY. Given only training codewords (no group), the learner:
   (1) takes their GF(2) span, (2) extracts the weight-8 words, (3) searches for permutations of the 24
   coordinates that map that block system onto itself (backtracking with Steiner-system propagation), and
   (4) computes the order of the group generated by a few random automorphisms (Schreier–Sims, sympy).
   Question: from how many codewords does it discover the full automorphism group, and what is it?
python run.py   (CPU, ~1 min)
"""
